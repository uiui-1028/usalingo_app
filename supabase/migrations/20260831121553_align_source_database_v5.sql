alter table public.word_relations enable row level security;

create policy content_concepts_select_authenticated
  on public.content_concepts for select to authenticated using (true);
create policy word_pronunciations_select_authenticated
  on public.word_pronunciations for select to authenticated using (true);
create policy example_audio_select_authenticated
  on public.example_audio for select to authenticated using (true);
