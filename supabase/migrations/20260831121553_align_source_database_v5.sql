  on public.word_forms for select to authenticated using (true);
create policy word_relations_select_authenticated
  on public.word_relations for select to authenticated using (true);

revoke all on table public.content_concepts, public.word_pronunciations,
  public.example_audio, public.word_forms, public.word_relations
  from public, anon, authenticated;
revoke all on sequence public.content_concepts_id_seq,
  public.word_pronunciations_id_seq, public.example_audio_id_seq
  from public, anon, authenticated;

grant select on table public.content_concepts, public.word_pronunciations,
