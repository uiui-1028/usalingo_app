grant select, insert, update, delete on table public.content_concepts,
  public.word_pronunciations, public.example_audio, public.word_forms,
  public.word_relations to service_role;
grant usage, select on sequence public.content_concepts_id_seq,
  public.word_pronunciations_id_seq, public.example_audio_id_seq to service_role;

comment on column public.words.source_note_guid is
  'Stable source-note identifier, such as the Anki note GUID.';
comment on column public.words.source_deck_code is
  'Stable operator-defined code for the source deck.';
comment on column public.words.source_position is
  'One-based source order; never use mutable Anki review due order.';
comment on table public.content_concepts is
  'Operator-managed example and media concepts from the V5 source database.';
comment on table public.word_pronunciations is
  'Zero or more pronunciations and word-audio assets for one canonical word.';
comment on table public.example_audio is
  'Zero or more audio assets for one example sentence.';
comment on table public.word_forms is
  'Operator-managed word forms stored as one JSON object per word.';
comment on table public.word_relations is
  'Operator-managed word relations stored as one JSON object per word.';

do $$
declare target_table text;
begin
  if (select count(*) from public.content_concepts where concept_code = 'simple') <> 1 then
    raise exception 'V5 alignment verification failed: simple concept is missing.';
  end if;
  if exists (select 1 from public.example_contents
    where concept_id is null or image_state is null or display_order is null) then
    raise exception 'V5 alignment verification failed: an example row was not backfilled.';
  end if;
  foreach target_table in array array['content_concepts','word_pronunciations',
    'example_audio','word_forms','word_relations'] loop
    if has_table_privilege('anon', format('public.%I', target_table), 'select')
      or not has_table_privilege('authenticated', format('public.%I', target_table), 'select')
      or has_table_privilege('authenticated', format('public.%I', target_table), 'insert')
      or has_table_privilege('authenticated', format('public.%I', target_table), 'update')
      or has_table_privilege('authenticated', format('public.%I', target_table), 'delete')
      or not has_table_privilege('service_role', format('public.%I', target_table), 'select')
      or not has_table_privilege('service_role', format('public.%I', target_table), 'insert')
      or not has_table_privilege('service_role', format('public.%I', target_table), 'update')
      or not has_table_privilege('service_role', format('public.%I', target_table), 'delete') then
      raise exception 'V5 alignment verification failed: grants for % are incorrect.', target_table;
    end if;
  end loop;
end
$$;

commit;
